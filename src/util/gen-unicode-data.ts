// Generates src/util/unicode-data.ts from the Unicode Character Database 15.0.0
// (vault-format.md: "Unicode version (for every appendix): 15.0.0" for the general
// categories, simple case folding and East Asian Width).
//
//   mkdir -p tmp/ucd && cd tmp/ucd && for f in extracted/DerivedGeneralCategory.txt \
//     EastAsianWidth.txt CaseFolding.txt; do curl -sSO https://www.unicode.org/Public/15.0.0/ucd/$f; done
//   bun run src/util/gen-unicode-data.ts tmp/ucd
//
// Not imported by passh itself.

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const CATEGORIES = [
  "Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe",
  "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co",
] as const;

/** One character per category in the encoded run list (never a base-36 digit). */
export const CATEGORY_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ!#%&";

function lines(file: string): Array<[number, number, string[]]> {
  const out: Array<[number, number, string[]]> = [];
  for (const raw of readFileSync(file, "utf8").split("\n")) {
    const l = raw.replace(/#.*/, "").trim();
    if (!l) continue;
    const parts = l.split(";").map((p) => p.trim());
    const range = parts[0]!;
    const [a, b] = range.includes("..") ? range.split("..") : [range, range];
    out.push([parseInt(a!, 16), parseInt(b!, 16), parts.slice(1)]);
  }
  return out;
}

function main(dir: string): void {
  // General categories: runs over all code points.
  const gc = new Uint8Array(0x110000); // 0 = Cn
  for (const [a, b, [cat]] of lines(join(dir, "DerivedGeneralCategory.txt"))) {
    const idx = CATEGORIES.indexOf(cat as (typeof CATEGORIES)[number]);
    if (idx < 0) throw new Error("unknown category " + cat);
    for (let c = a; c <= b; c++) gc[c] = idx;
  }
  let runs = "";
  let prevStart = 0;
  let nruns = 0;
  for (let c = 0; c < 0x110000; c++) {
    if (c === 0 || gc[c] !== gc[c - 1]) {
      runs += (c - prevStart).toString(36) + CATEGORY_CHARS[gc[c]!];
      prevStart = c;
      nruns++;
    }
  }

  // East Asian Width: W or F. Unlisted code points are N, except the unassigned ones in
  // the CJK blocks and planes 2–3 named in the file's header, which default to W.
  const eaw = new Uint8Array(0x110000);
  const listed = new Uint8Array(0x110000);
  for (const [a, b, [w]] of lines(join(dir, "EastAsianWidth.txt"))) {
    for (let c = a; c <= b; c++) {
      listed[c] = 1;
      eaw[c] = w === "W" || w === "F" ? 1 : 0;
    }
  }
  for (const [a, b] of [[0x3400, 0x4dbf], [0x4e00, 0x9fff], [0xf900, 0xfaff], [0x20000, 0x2fffd], [0x30000, 0x3fffd]] as const) {
    for (let c = a; c <= b; c++) if (!listed[c]) eaw[c] = 1;
  }
  const wide: number[] = [];
  for (let c = 0; c < 0x110000; c++) {
    if (eaw[c] && (c === 0 || !eaw[c - 1])) wide.push(c);
    if (eaw[c] && (c === 0x10ffff || !eaw[c + 1])) wide.push(c);
  }

  // Simple case folding: statuses C and S.
  const pairs: Array<[number, number]> = [];
  for (const [a, , [status, to]] of lines(join(dir, "CaseFolding.txt"))) {
    if (status !== "C" && status !== "S") continue;
    pairs.push([a, parseInt(to!, 16)]);
  }
  pairs.sort((x, y) => x[0] - y[0]);
  // Runs of (start, count, stride, delta).
  const fold: number[] = [];
  for (let i = 0; i < pairs.length; ) {
    const [s, d] = pairs[i]!;
    const delta = d - s;
    let stride = 0;
    let count = 1;
    if (i + 1 < pairs.length && pairs[i + 1]![1] - pairs[i + 1]![0] === delta) {
      stride = pairs[i + 1]![0] - s;
      count = 2;
      while (i + count < pairs.length) {
        const [s2, d2] = pairs[i + count]!;
        if (d2 - s2 !== delta || s2 - pairs[i + count - 1]![0] !== stride) break;
        count++;
      }
    }
    fold.push(s, count, stride || 1, delta);
    i += count;
  }

  const out = `// Generated by src/util/gen-unicode-data.ts from the Unicode Character Database 15.0.0
// (DerivedGeneralCategory.txt, EastAsianWidth.txt, CaseFolding.txt). Do not edit.

/** General categories, index = code in GC_RUNS. */
export const GC_NAMES = ${JSON.stringify(CATEGORIES)} as const;

/** Category runs: base-36 distance from the previous run's start, then one category letter. ${nruns} runs. */
export const GC_RUNS =
  ${JSON.stringify(runs)};

/** Letters of GC_RUNS, in GC_NAMES order. */
export const GC_CHARS = ${JSON.stringify(CATEGORY_CHARS)};

/** East Asian Width W or F: inclusive ranges [first, last, first, last, …]. */
export const WIDE_RANGES: readonly number[] = ${JSON.stringify(wide)};

/** Simple case folding (C + S): runs [start, count, stride, delta, …]; c ↦ c + delta. */
export const FOLD_RUNS: readonly number[] = ${JSON.stringify(fold)};
`;
  writeFileSync(resolve(import.meta.dir, "unicode-data.ts"), out);
  console.log(`runs ${nruns}, wide ranges ${wide.length / 2}, fold pairs ${pairs.length} in ${fold.length / 4} runs, ${out.length} bytes`);
}

if (import.meta.main) main(process.argv[2] ?? "tmp/ucd");
